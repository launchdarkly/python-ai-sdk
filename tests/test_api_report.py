"""The committed API reports are current, and the generator records what callers see."""

from __future__ import annotations

import textwrap
from pathlib import Path

import pytest

from scripts import api_report


def test_committed_reports_are_current(capsys: pytest.CaptureFixture[str]) -> None:
    # A stale report means a public name or signature changed without its report.
    assert api_report.main(["--check"]) == 0, capsys.readouterr().out


def write(path: Path, source: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(source))


@pytest.fixture
def workspace(tmp_path: Path) -> Path:
    src = tmp_path / "packages/demo/src/demo_sdk"
    write(
        src / "__init__.py",
        """
        from json import JSONDecoder
        from demo_sdk.run import run
        from demo_sdk.types import Options, Result, Usage, make, LIMIT

        __all__ = ["JSONDecoder", "LIMIT", "Options", "Result", "Usage", "make", "run"]
        """,
    )
    write(
        src / "run.py",
        """
        async def run(key: str, *, retries: int = 3, **extra: object) -> str:
            return key
        """,
    )
    write(
        src / "types.py",
        """
        from dataclasses import dataclass

        LIMIT: int = 10
        Options = dict[str, object]

        @dataclass(frozen=True)
        class Usage:
            total: int = 0
            _secret: int = 0

        class Result:
            def __init__(self, value: str) -> None:
                self.value = value

            @property
            def size(self) -> int:
                return len(self.value)

            @classmethod
            def empty(cls) -> "Result":
                return cls("")

            def _hidden(self) -> None: ...

        def make(value: str, /, *items: int) -> Result:
            return Result(value)
        """,
    )
    write(src / "experimental/__init__.py", "")
    write(
        src / "experimental/beta.py",
        """
        def try_it() -> None: ...

        __all__ = ["try_it"]
        """,
    )
    write(tmp_path / "packages/umbrella/src/launchdarkly_ai_python/__init__.py", "")
    return tmp_path


def test_report_contents(workspace: Path) -> None:
    reports = api_report.reports(workspace)
    package = workspace / "packages/demo"
    assert set(reports) == {
        package / "api-report/demo_sdk.txt",
        package / "api-report/demo_sdk.experimental.beta.txt",
    }
    assert reports[package / "api-report/demo_sdk.txt"] == textwrap.dedent(
        """\
        # Public API of demo_sdk. Generated by `make api-report`; do not edit.
        JSONDecoder = json.JSONDecoder  [re-export]
        LIMIT: int = 10
        make(value: str, /, *items: int) -> Result
        Options = dict[str, object]
        Result  [class]
          __init__(value: str)
          empty() -> Result  [classmethod]
          size: int  [property]
          value = value
        run(key: str, *, retries: int = 3, **extra: object) -> str  [async]
        Usage  [class, @dataclass(frozen=True)]
          __init__(total: int = 0, _secret: int = 0)
          total: int = 0
        """
    )
    assert reports[package / "api-report/demo_sdk.experimental.beta.txt"].endswith(
        "try_it() -> None\n"
    )


def test_an_imported_name_wins_over_a_submodule(workspace: Path) -> None:
    # `from demo_sdk.run import run` binds the function, not the `run` module.
    text = api_report.reports(workspace)[
        workspace / "packages/demo/api-report/demo_sdk.txt"
    ]
    assert "run(key: str" in text
    assert "run  [module]" not in text


def test_writing_removes_a_stale_report(
    workspace: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(api_report, "ROOT", workspace)
    stale = workspace / "packages/demo/api-report/demo_sdk.gone.txt"
    stale.parent.mkdir()
    stale.write_text("old\n")
    assert api_report.main([]) == 0
    assert not stale.exists()
    assert api_report.main(["--check"]) == 0


def test_a_module_without_all_fails(workspace: Path) -> None:
    write(
        workspace / "packages/demo/src/demo_sdk/experimental/beta.py",
        "def try_it() -> None: ...\n",
    )
    with pytest.raises(SystemExit, match="no __all__"):
        api_report.reports(workspace)


def test_an_undefined_name_in_all_fails(workspace: Path) -> None:
    write(
        workspace / "packages/demo/src/demo_sdk/experimental/beta.py",
        '__all__ = ["missing"]\n',
    )
    with pytest.raises(SystemExit, match="missing is in __all__ but not defined"):
        api_report.reports(workspace)


def test_dunders_and_class_keywords_are_reported(workspace: Path) -> None:
    write(
        workspace / "packages/demo/src/demo_sdk/experimental/beta.py",
        """
        from typing import TypedDict

        class Config(TypedDict, total=False):
            model: str

        class Runner:
            def __init__(self) -> None: ...
            def __call__(self, key: str) -> int: ...
            def _private(self) -> None: ...

        __all__ = ["Config", "Runner"]
        """,
    )
    text = api_report.reports(workspace)[
        workspace / "packages/demo/api-report/demo_sdk.experimental.beta.txt"
    ]
    assert text.endswith(
        textwrap.dedent(
            """\
            Config(TypedDict, total=False)  [class]
              model: str
            Runner  [class]
              __init__()
              __call__(key: str) -> int
            """
        )
    )
