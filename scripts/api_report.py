"""Generate or check the API report of every public module.

A report records each name in a module's ``__all__`` with its full signature, one
unindented line per name; a class's public members follow on lines indented by two
spaces. Reports live at ``packages/<package>/api-report/<module>.txt`` and are the
package's public API contract: any change to a public name or signature shows up as a
diff in a committed file.

    uv run python scripts/api_report.py           # write every report
    uv run python scripts/api_report.py --check   # fail if any report is stale
"""

from __future__ import annotations

import difflib
import sys
from pathlib import Path
from typing import Any

import griffe

ROOT = Path(__file__).resolve().parent.parent
# Re-exports the core package unchanged, so the core report covers it.
SKIP = {"launchdarkly_ai_python"}
HEADER = "# Public API of {module}. Generated by `make api-report`; do not edit.\n"


def public_modules(root: Path) -> dict[str, Path]:
    """Map each reported module to its package directory: each package root, and
    each module of a package's ``experimental`` subpackage."""
    found: dict[str, Path] = {}
    for init in sorted(root.glob("packages/*/src/*/__init__.py")):
        package_dir, name = init.parents[2], init.parent.name
        if name in SKIP:
            continue
        found[name] = package_dir
        experimental = init.parent / "experimental"
        for sub in sorted(experimental.glob("*.py")) if experimental.is_dir() else []:
            if not sub.name.startswith("_"):
                found[f"{name}.experimental.{sub.stem}"] = package_dir
    return found


def resolve(loader: griffe.GriffeLoader, module: Any, name: str) -> Any:
    """Return what ``from module import name`` gives an application.

    An imported name wins over a submodule of the same name, as it does at run
    time (``from .graph import graph`` binds the function, not the module).
    """
    obj = module.members.get(name)
    path = module.imports.get(name)
    if path:
        try:
            obj = loader.modules_collection.get_member(path)
        except KeyError:  # imported from another distribution; keep the alias
            pass
    if obj is None:
        raise SystemExit(f"{module.path}: {name} is in __all__ but not defined")
    while obj.is_alias:
        try:
            obj = obj.target
        except griffe.AliasResolutionError:
            return obj
    return obj


# Labels that change how a caller uses a name; decorators are shown separately.
SHOWN_LABELS = {"abstractmethod", "async", "classmethod", "staticmethod"}


# Decorators already shown as a label, or as the [property] tag.
LABEL_DECORATORS = {"abstractmethod", "classmethod", "property", "staticmethod"}


def tags(obj: Any, *extra: str) -> str:
    labels = [*extra, *sorted(obj.labels & SHOWN_LABELS)]
    decorators = [
        f"@{d.value}"
        for d in getattr(obj, "decorators", [])
        if str(d.value).split(".")[-1] not in LABEL_DECORATORS | {"setter", "deleter"}
    ]
    shown = labels + decorators
    return f"  [{', '.join(shown)}]" if shown else ""


def call(obj: Any, name: str) -> str:
    """``name(params) -> returns``, under the name the caller uses."""
    signature = obj.signature()
    return (
        name + signature[len(obj.name) :]
        if signature.startswith(obj.name)
        else signature
    )


def describe(obj: Any, name: str, indent: str = "") -> list[str]:
    if obj.is_alias:  # an unresolved re-export from another distribution
        return [f"{indent}{name} = {obj.target_path}  [re-export]"]
    if obj.is_module:
        return [f"{indent}{name}  [module]"]
    if obj.is_function:
        if "property" in obj.labels:
            return [f"{indent}{name}: {obj.returns}{tags(obj, 'property')}"]
        return [f"{indent}{call(obj, name)}{tags(obj)}"]
    if obj.is_type_alias:
        return [f"{indent}{name} = {obj.value}  [type]"]
    if obj.is_attribute:
        annotation = f": {obj.annotation}" if obj.annotation is not None else ""
        if "property" in obj.labels:
            return [f"{indent}{name}{annotation}{tags(obj, 'property')}"]
        value = f" = {obj.value}" if obj.value is not None else ""
        return [f"{indent}{name}{annotation}{value}{tags(obj)}"]
    # A class: its bases and keywords (e.g. ``total=False``), then its constructor and
    # public members, dunders included.
    args = [*map(str, obj.bases), *(f"{k}={v}" for k, v in obj.keywords.items())]
    bases = f"({', '.join(args)})" if args else ""
    lines = [f"{indent}{name}{bases}{tags(obj, 'class')}"]
    if "__init__" in obj.members:
        lines.append(f"{indent}  {call(obj, '__init__')}")
    members = sorted(
        (
            m
            for m in obj.members.values()
            if m.name != "__init__"
            and (not m.name.startswith("_") or m.name.endswith("__"))
        ),
        key=lambda m: m.name.lower(),
    )
    for member in members:
        lines += describe(member, member.name, indent + "  ")
    return lines


def report(loader: griffe.GriffeLoader, module_path: str) -> str:
    module = loader.modules_collection.get_member(module_path)
    if not module.exports:
        raise SystemExit(f"{module_path}: no __all__")
    lines = [HEADER.format(module=module_path).rstrip("\n")]
    for name in sorted(module.exports, key=lambda n: (n.lower(), n)):
        lines += describe(resolve(loader, module, str(name)), str(name))
    return "\n".join(lines) + "\n"


def reports(root: Path = ROOT) -> dict[Path, str]:
    """Return {report path: contents} for every public module under ``root``."""
    modules = public_modules(root)
    loader = griffe.GriffeLoader(
        search_paths=sorted(str(p) for p in root.glob("packages/*/src"))
    )
    for top in sorted({m.split(".")[0] for m in modules}):
        loader.load(top)
    loader.resolve_aliases(external=False, implicit=False)
    return {
        package / "api-report" / f"{module}.txt": report(loader, module)
        for module, package in modules.items()
    }


def main(argv: list[str]) -> int:
    expected = reports()
    if argv != ["--check"]:
        for path, text in expected.items():
            path.parent.mkdir(exist_ok=True)
            path.write_text(text)
        print(f"wrote {len(expected)} API reports")
        return 0
    stale = []
    for path in sorted(set(expected) | set(ROOT.glob("packages/*/api-report/*.txt"))):
        current = path.read_text() if path.exists() else ""
        if current != expected.get(path, ""):
            stale.append(path)
            rel = str(path.relative_to(ROOT))
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    expected.get(path, "").splitlines(keepends=True),
                    f"{rel} (committed)",
                    f"{rel} (from the code)",
                )
            )
    if stale:
        print(
            f"\n{len(stale)} API report(s) out of date: run `make api-report` and commit the result."
        )
        return 1
    print(f"{len(expected)} API reports are current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
